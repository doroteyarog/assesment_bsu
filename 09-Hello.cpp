#include <iostream>     // Includes the input/output stream library
using namespace std;    // Allows use of standard library names without std::

// Function definition that prints "Hello"
void hello() {          // Defines a function named 'hello' that returns nothing (void)
    cout << "Hello" << endl;   // Prints the word "Hello" followed by a newline
}

int main() {            // Main function where program execution begins

    hello();            // Calls the function 'hello' so it executes

    return 0;           // Returns 0 to signal successful program termination
}
